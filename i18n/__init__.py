"""Language registry and per-update language context.

Every user-facing string lives in a catalog module: :mod:`i18n.ar` or
:mod:`i18n.en`.  Handlers keep importing ``strings`` (a thin facade) and the
catalog is resolved from a :mod:`contextvars` value, so a handler never has to
thread a ``lang`` argument through every call.

Three rules keep this predictable:

1. ``i18n.set_language(lang)`` is called once per update by the middleware,
   after loading the user's stored language.
2. Background work (alerts, digests, admin notices) wraps each recipient in
   ``with i18n.use(lang):`` so one task can never leak its language into the
   next.
3. The default is Arabic, which keeps legacy tests and any pre-language user
   on the language the bot shipped with.
"""

from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager
from contextvars import ContextVar
from types import ModuleType

from . import ar, en

#: Languages the interface is officially available in.
SUPPORTED_LANGUAGES: tuple[str, ...] = ("ar", "en")

#: Used whenever the user has not chosen yet and for admin/system messages.
DEFAULT_LANGUAGE = "ar"

#: Native names, shown in the language picker.
LANGUAGE_NAMES: dict[str, str] = {"ar": "العربية", "en": "English"}

#: Telegram language codes that should map to each catalog.
_LANGUAGE_ALIASES: dict[str, str] = {
    "ar": "ar",
    "en": "en",
    "en-us": "en",
    "en-gb": "en",
}

_CATALOGS: dict[str, ModuleType] = {"ar": ar, "en": en}

_current: ContextVar[str] = ContextVar("cinema_radar_language", default=DEFAULT_LANGUAGE)

#: The admin is a single operator: their language applies to admin/system
#: messages even when they are generated by a background task.
_admin_language: str = DEFAULT_LANGUAGE


def normalize(value: object) -> str:
    """Map any Telegram/locale value to a supported language code."""

    raw = str(value or "").strip().lower().replace("_", "-")
    if not raw:
        return DEFAULT_LANGUAGE
    if raw in _LANGUAGE_ALIASES:
        return _LANGUAGE_ALIASES[raw]
    base = raw.split("-", 1)[0]
    return base if base in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def catalog(lang: object = None) -> ModuleType:
    """Return the catalog module for ``lang`` (defaults to the current one)."""

    code = normalize(lang) if lang is not None else get_language()
    return _CATALOGS.get(code, _CATALOGS[DEFAULT_LANGUAGE])


def get_language() -> str:
    """Current language for this context (``ar`` unless changed)."""

    return normalize(_current.get())


# Backwards-friendly alias: some call sites read naturally as ``current_lang()``.
def current_language() -> str:
    return get_language()


def set_language(lang: object) -> str:
    """Set the language for the rest of this task/update. Returns the code."""

    code = normalize(lang)
    _current.set(code)
    return code


@contextmanager
def use(lang: object) -> Iterator[ModuleType]:
    """Temporarily render in ``lang`` (used per alert recipient)."""

    token = _current.set(normalize(lang))
    try:
        yield catalog()
    finally:
        _current.reset(token)


def for_language(lang: object) -> ModuleType:
    """Explicit catalog access, for startup code outside any request context."""

    return catalog(lang)


def language_name(lang: object) -> str:
    return LANGUAGE_NAMES.get(normalize(lang), LANGUAGE_NAMES[DEFAULT_LANGUAGE])


def admin_language() -> str:
    return _admin_language


def set_admin_language(lang: object) -> str:
    global _admin_language
    _admin_language = normalize(lang)
    return _admin_language


__all__ = [
    "DEFAULT_LANGUAGE",
    "LANGUAGE_NAMES",
    "SUPPORTED_LANGUAGES",
    "admin_language",
    "catalog",
    "current_language",
    "for_language",
    "get_language",
    "language_name",
    "normalize",
    "set_admin_language",
    "set_language",
    "use",
]
